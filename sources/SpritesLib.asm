; Данные спрайта 16x16 (каждая строка — 2 байта)
Sprite_Alien:
    DB 0x03, 0xC0    ;   00000011 11000000
    DB 0x0F, 0xF0    ;   00001111 11110000
    DB 0x1E, 0x78    ;   00011110 01111000
    DB 0x3C, 0x3C    ;   00111100 00111100
    DB 0x7F, 0xFE    ;   01111111 11111110
    DB 0x6D, 0xB6    ;   01101101 10110110  (Глаза)
    DB 0x7F, 0xFE    ;   01111111 11111110
    DB 0x3E, 0x7C    ;   00111110 01111100
    DB 0x1F, 0xF8    ;   00011111 11111000
    DB 0x0C, 0x30    ;   00001100 00110000
    DB 0x1E, 0x78    ;   00011110 01111000
    DB 0x33, 0xCC    ;   00110011 11001100
    DB 0x61, 0x86    ;   01100001 10000110
    DB 0x40, 0x02    ;   01000000 00000010
    DB 0xC0, 0x03    ;   11000000 00000011
    DB 0xC0, 0x03    ;   11000000 00000011


; *****************************************************************************
; DrawSprite16x16 — выводит спрайт 16x16 попиксельно в режиме XOR
;   Input:  B = Y (0..176) — координата верхней строки
;           C = X (0..240) — координата левого края
;           IX = Адрес данных спрайта (32 байта)
;   Портит: A, BC, DE, HL
; *****************************************************************************
DrawSprite16x16:
    ld   a, c
    and  7                  
    ld   iyh, a             ; IYH = смещение внутри байта (X % 8, от 0 до 7)

    ld   a, c
    rrca
    rrca
    rrca
    and  0x1F
    ld   iyl, a             ; IYL = номер начального столбца на экране (X / 8)

    ld   c, 16              ; Счётчик строк: нам нужно обработать 16 строк в высоту

_sprite_line_loop:
    push bc                 ; [Стек: сохраняем счётчик строк и Y]

    ; 1. Мгновенно находим базовый адрес строки экрана в HL
    ld   d, HIGH Table_H
    ld   e, b               ; E = текущий Y
    ld   a, (de)
    ld   h, a               ; H экрана готов

    ld   d, HIGH Table_L
    ld   a, (de)
    ld   l, a               ; L экрана (базовый) готов

    ; 2. Добавляем смещение столбца (X / 8)
    ld   a, iyl
    or   l
    ld   l, a               ; HL = точный адрес левого байта на экране!

    ; 3. Загружаем 2 байта текущей строки спрайта из памяти IX
    ld   d, (ix+0)          ; D = левый байт спрайта
    ld   e, (ix+1)          ; E = правый байт спрайта
    
    ; 4. Попиксельный сдвиг налету!
    ; Нам нужно сдвинуть пару DE вправо на количество пикселей, записанное в IYH.
    ; Чтобы освободившиеся слева биты стали нулями, вводим третий байт — C_Byte (будет в C)
    ld   a, iyh             ; Сколько бит сдвигаем?
    and  a
    jr   z, _sprite_no_shift ; Если смещение ровно 0, сдвиг пропускаем!

    ld   c, 0               ; C будет хранить вылетевший хвост справа (3-й байт)
    ld   b, a               ; Счётчик сдвигов для текущей строки

_sprite_shift_loop:
    ; Сдвигаем 24-битную структуру [D][E][C] вправо на 1 бит
    srl  d                  ; Старший бит D становится 0, младший уходит в Carry
    rr   e                  ; Carry уходит в старший бит E, младший — в Carry
    rr   c                  ; Carry уходит в старший бит C
    djnz _sprite_shift_loop ; Повторяем, пока не сдвинем на X % 8 пикселей

_sprite_no_shift:
    ; Теперь у нас готово до 3 байт графики для наложения:
    ; D — левый кусок, E — средний кусок, C — правый хвост (если был сдвиг)

    ; --- Наложение 1-го (левого) байта ---
    ld   a, d
    xor  (hl)               ; Применяем XOR к экрану
    ld   (hl), a
    inc  l                  ; Шаг на следующий байт экрана вправо

    ; --- Наложение 2-го (среднего) байта ---
    ld   a, e
    xor  (hl)               ; Применяем XOR к экрану
    ld   (hl), a

    ; --- Наложение 3-го (правого) байта (только если был сдвиг) ---
    ld   a, iyh
    and  a
    jr   z, _sprite_next_line ; Если сдвига не было, 3-й байт пуст, пропускаем
    
    inc  l                  ; Шаг на 3-й байт экрана вправо
    ld   a, c
    xor  (hl)               ; Накладываем остаток
    ld   (hl), a

_sprite_next_line:
    ; Переходим к следующей строке данных спрайта (+2 байта к указателю)
    inc  ix
    inc  ix

    pop  bc                 ; [Стек: восстановили счётчик строк и Y]
    inc  b                  ; Y = Y + 1 (переходим на следующую строку экрана вниз)
    dec  c                  ; Уменьшаем счётчик строк (от 16 до 0)
    white_spr_loop EQU $
    jr   nz, _sprite_line_loop

    ret


    DEVICE ZXSPECTRUM48
    ORG 32768

Start:
    ; 1. Включаем стандартный режим прорисовки и генерируем фон
    ld   a, 1
    ld   (mode_draw), a
    call ApplyDrawMode

    ; Нарисуем сетку прямоугольников для красивого фона
    ld   bc, 0x0505
    ld   de, 0x2020
    ld   h, 4
.bg_loop:
    push bc
    push de
    push hl
    call DrawRect
    pop  hl
    pop  de
    pop  bc
    ld   a, c
    add  a, 40
    ld   c, a
    dec  h
    jr   nz, .bg_loop

    ; 2. ПЕРЕКЛЮЧАЕМ ДВИЖОК В РЕЖИМ XOR ДЛЯ СПРАЙТОВ
    ; (Функция DrawSprite16x16 жестко использует XOR внутри, но для стабильности 
    ;  выставим флаг, чтобы другие элементы не портили логику).
    ld   a, 2
    ld   (mode_draw), a
    call ApplyDrawMode

    ; Начальные координаты пришельца
    ld   b, 10              ; Y = 10
    ld   c, 0               ; X = 0 (начинаем с левого края)

.animation_loop:
    ; --- СТАДИЯ A: РИСУЕМ СПРАЙТ НА НОВОМ МЕСТЕ ---
    push bc
    ld   ix, Sprite_Alien   ; Загружаем адрес графики пришельца
    call DrawSprite16x16    ; Нарисовали пришельца поверх фона!
    pop  bc

    ; Небольшая задержка, чтобы человеческий глаз успел увидеть кадр
    call Delay_Frame

    ; --- СТАДИЯ Б: СТИРАЕМ СПРАЙТ ПОВТОРНЫМ XOR В ТЕХ ЖЕ КООРДИНАТАХ ---
    push bc
    ld   ix, Sprite_Alien   ; Указатель нужно восстановить, так как DrawSprite его увеличил
    call DrawSprite16x16    ; ПОВТОРНЫЙ XOR СТЁР ПРИШЕЛЬЦА И ИДЕАЛЬНО ВОССТАНОВИЛ ФОН!
    pop  bc

    ; --- СТАДИЯ В: СДВИГАЕМ КООРДИНАТУ ---
    inc  c                  ; Сдвигаем X на 1 пиксель вправо!
    ld   a, c
    cp   220                ; Двигаем, пока не дойдем до правого края экрана
    jr   nz, .animation_loop

    ; Пришелец долетел до конца, зависаем
    jr   $

; Простая задержка для фреймрейта
Delay_Frame:
    push bc
    ld   bc, 0x1AFF
.d_loop:
    white_delay EQU $
    dec  bc
    ld   a, b
    or   c
    jr   nz, .d_loop
    pop  bc
    ret

; Подключаем графику пришельца
Sprite_Alien:
    DB 0x03, 0xC0, 0x0F, 0xF0, 0x1E, 0x78, 0x3C, 0x3C
    DB 0x7F, 0xFE, 0x6D, 0xB6, 0x7F, 0xFE, 0x3E, 0x7C
    DB 0x1F, 0xF8, 0x0C, 0x30, 0x1E, 0x78, 0x33, 0xCC
    DB 0x61, 0x86, 0x40, 0x02, 0xC0, 0x03, 0xC0, 0x03

