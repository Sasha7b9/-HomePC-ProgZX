SetPoint:
    ; Вход: B = Y (0..191), C = X (0..255)
    ; Портит: A, DE, HL

    ; 1. Мгновенно берём готовый H для нашей строки Y из таблицы
    ld   d, HIGH Table_H
    ld   e, b
    ld   a, (de)
    ld   h, a               ; В H теперь точный старший байт адреса экрана

    ; 2. Мгновенно берём базовый L для нашей строки Y из таблицы
    ld   d, HIGH Table_L
    ; e уже равен b
    ld   a, (de)            ; Получили RRR00000 для этой строки
    ld   l, a

    ; 3. Добавляем к L координату X/8
    ld   a, c
    rrca
    rrca
    rrca                    
    and  0x1F               ; A = X / 8
    or   l                  
    ld   l, a               ; HL полностью готов к записи!

    ; 4. Мгновенно берём маску пикселя из таблицы X
    ld   d, HIGH BitTable
    ld   e, c
    ld   a, (de)            ; A = маска

    ; 5. Вывод на экран
    or   (hl)
    ld   (hl), a
    ret

; *************************************************************
; DrawHLine — рисует горизонтальную линию
;   Input:  B = Y (0..191)
;           C = X (0..255) — начальный пиксель
;           A = L (1..255) — длина в пикселях
;   Портит: A, BC, DE, HL
; *************************************************************
DrawHLine:
    and  a
    ret  z                  ; Если длина 0, сразу выходим

    push af                 ; [Стек: сохраняем длину линии]
    
    ; --- 1. Вычисляем адрес байта с помощью таблиц Y через HIGH ---
    ld   d, HIGH Table_H
    ld   e, b
    ld   a, (de)
    ld   h, a               ; H готов (старший байт адреса экрана)

    ld   d, HIGH Table_L
    ; e по-прежнему равен b
    ld   a, (de)
    ld   l, a               ; L готов (базовый младший байт строки)

    ld   a, c
    rrca
    rrca
    rrca
    and  0x1F               ; A = X / 8 (столбец 0..31)
    or   l
    ld   l, a               ; HL = точный адрес начального байта на экране

    ; --- 2. Вычисляем параметры для первого байта ---
    ld   a, c
    and  7                  ; A = X % 8 (смещение внутри байта, 0..7)
    ld   e, a               ; E = X % 8

    ; Сколько пикселей свободно в первом байте? (8 - E)
    ld   a, 8
    sub  e
    ld   b, a               ; B = сколько пикселей поместится в 1-й байт

    ; Теперь восстанавливаем длину линии из стека в регистр D
    pop  af                 ; [Стек: пуст] Извлекаем длину
    ld   d, a               ; D = длина линии в пикселях

    ; Проверяем, помещается ли вся линия в один этот байт?
    cp   b
    jr   c, .one_byte       ; Если L < (8-E) -> линия короткая, внутри 1 байта
    jr   z, .one_byte_full  ; Если L == (8-E) -> заполняем 1-й байт ровно до конца

    ; --- 3. Сценарий: Линия длиннее одного байта ---
    ; Рисуем первый байт (маска справа от позиции E)
    ld   a, e
    push hl                 ; Сохраняем HL экрана перед расчетом адреса маски
    ld   hl, MaskRightTable
    add  a, l
    ld   l, a
    jr   nc, .no_c1
    inc  h
.no_c1:
    ld   a, (hl)            ; Получили маску пикселей «от E до конца байта»
    pop  hl                 ; Восстановили оригинальный HL экрана
    
    or   (hl)
    ld   (hl), a            ; Записали измененный первый байт на экран
    inc  l                  ; Переходим к следующему байту по горизонтали

    ; Вычисляем оставшуюся длину линии: D = D - B
    ld   a, d
    sub  b
    ld   d, a               ; D = сколько пикселей осталось нарисовать

    ; --- Цикл заливки целых байт (по 8 пикселей) ---
.whole_loop:
    ld   a, d
    cp   8
    jr   c, .last_byte      ; Если осталось меньше 8 пикселей -> переходим к последнему
    
    ld   (hl), 0xFF         ; Заливаем все 8 пикселей
    inc  l                  ; Переходим к следующему байту
    
    ld   a, d
    sub  8
    ld   d, a               ; Уменьшаем остаток длины
    jr   .whole_loop

    ; Рисуем последний кусочек линии (остаток пикселей слева в байте)
.last_byte:
    ld   a, d
    and  a
    ret  z                  ; Если остаток ровно 0, то всё готово!
    
    ld   e, a
    push hl                 ; Сохраняем HL экрана
    ld   hl, MaskLeftTable-1 ; Смещение -1, так как индекс от 1 до 7
    add  a, l
    ld   l, a
    jr   nc, .no_c_lb
    inc  h
.no_c_lb:
    ld   a, (hl)            ; Получили маску
    pop  hl                 ; Восстановили HL экрана
    
    or   (hl)
    ld   (hl), a
    ret

    ; --- Сценарий: Линия заканчивается ровно на границе первого байта ---
.one_byte_full:
    ld   a, e
    push hl                 ; Сохраняем HL экрана
    ld   hl, MaskRightTable
    add  a, l
    ld   l, a
    jr   nc, .no_c2
    inc  h
.no_c2:
    ld   a, (hl)
    pop  hl                 ; Восстановили HL экрана
    or   (hl)
    ld   (hl), a
    ret

    ; --- Сценарий: Вся линия лежит внутри ОДНОГО байта ---
.one_byte:
    push hl                 ; Сохраняем адрес экрана

    ; 1. Получаем маску правого края (от X до конца байта)
    ld   a, e               ; e = X % 8
    ld   hl, MaskRightTable
    add  a, l
    ld   l, a
    jr   nc, .m1
    inc  h
.m1:
    ld   a, (hl)
    ld   b, a               ; B = маска справа

    ; 2. Получаем маску левого края (длина линии внутри байта)
    ld   a, c
    and  7
    add  a, d               ; Количество занятых пикселей слева
    ld   hl, MaskLeftTable
    add  a, l
    ld   l, a
    jr   nc, .m2
    inc  h
.m2:
    ld   a, (hl)
    and  b                  ; A = финальная изолированная маска отрезка
    ld   b, a               ; Временно прячем маску в B
    
    ; 3. Восстанавливаем экранный адрес и накладываем пиксели
    pop  hl                 
    ld   a, b               ; Возвращаем маску в A
    or   (hl)
    ld   (hl), a
    ret

; ============================================================
; ТАБЛИЦЫ МАСОК И АДРЕСОВ
; ============================================================

    ALIGN 256
BitTable:
    REPT 32
    DB 0x80, 0x40, 0x20, 0x10, 0x08, 0x04, 0x02, 0x01
    ENDR

    ALIGN 256
Table_H:
_Y  = 0
    DUP 192
        DB 0x40 + ((_Y / 64) * 8) + (_Y % 8)
_Y  = _Y + 1
    EDUP
    REPT 64
        DB 0
    ENDR

    ALIGN 256
Table_L:
_Y  = 0
    DUP 192
        DB ((_Y % 64) / 8) * 32
_Y  = _Y + 1
    EDUP
    REPT 64
        DB 0
    ENDR

    ALIGN 8
MaskRightTable:
    DB 0xFF, 0x7F, 0x3F, 0x1F, 0x0F, 0x07, 0x03, 0x01

    ALIGN 8
MaskLeftTable:
    DB 0x00, 0x80, 0xC0, 0xE0, 0xF0, 0xF8, 0xFC, 0xFE, 0xFF
