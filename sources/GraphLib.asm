SetPoint:
    ; Вход: B = Y (0..191), C = X (0..255)
    ; Портит: A, DE, HL

    ld   d, HIGH Table_H
    ld   e, b
    ld   a, (de)
    ld   h, a               ; H готов

    ld   d, HIGH Table_L
    ld   a, (de)            
    ld   l, a               ; L готов

    ld   a, c
    rrca
    rrca
    rrca                    
    and  0x1F               ; A = X / 8
    or   l                  
    ld   l, a               

    ld   d, HIGH BitTable
    ld   e, c
    ld   a, (de)            ; A = маска

    or   (hl)
    ld   (hl), a
    ret

; *************************************************************
; DrawHLine — рисует горизонтальную линию
;   Input:  B = Y (0..191)
;           C = X (0..255) — начальный пиксель
;           A = L (1..255) — длина в пикселях
;   Портит: A, BC, DE, HL
; *************************************************************
DrawHLine:
    and  a
    ret  z                  ; Если длина 0, сразу выходим

    push af                 ; [Стек: сохраняем длину линии]
    
    ; --- 1. Вычисляем адрес байта с помощью таблиц Y ---
    ld   d, HIGH Table_H
    ld   e, b
    ld   a, (de)
    ld   h, a               ; H готов

    ld   d, HIGH Table_L
    ld   a, (de)
    ld   l, a               ; L готов

    ld   a, c
    rrca
    rrca
    rrca
    and  0x1F               ; A = X / 8 (столбец 0..31)
    or   l
    ld   l, a               ; HL = точный адрес начального байта на экране

    ; --- 2. Вычисляем параметры для первого байта ---
    ld   a, c
    and  7                  ; A = X % 8 (смещение внутри байта, 0..7)
    ld   e, a               ; E = X % 8

    ; Сколько пикселей свободно в первом байте? (8 - E)
    ld   a, 8
    sub  e
    ld   b, a               ; B = сколько пикселей поместится в 1-й байт

    ; Теперь восстанавливаем длину линии из стека в регистр D
    pop  af                 ; [Стек: пуст] Извлекаем длину
    ld   d, a               ; D = длина линии в пикселях

    ; Проверяем, помещается ли вся линия в один этот байт?
    cp   b
    jr   c, .one_byte       ; Если L < (8-E) -> внутри 1 байта
    jr   z, .one_byte_full  ; Если L == (8-E) -> заполняем 1-й байт до конца

    ; --- 3. Сценарий: Линия длиннее одного байта ---
    ; Рисуем первый байт (маска справа от позиции E)
    ld   a, HIGH MaskRightTable
    ld   ixh, a             ; Используем старший байт выровненной таблицы
    ld   a, (ix+0)          ; Чтение маски напрямую по индексу E (так как E равен X%8)
    
    or   (hl)
    ld   (hl), a            ; Записали первый байт на экран
    inc  l                  ; Переходим к следующему байту по горизонтали

    ; Вычисляем оставшуюся длину линии: D = D - B
    ld   a, d
    sub  b
    ld   d, a               ; D = сколько пикселей осталось нарисовать

    ; --- Цикл заливки целых байт (по 8 пикселей) ---
.whole_loop:
    ld   a, d
    cp   8
    jr   c, .last_byte      ; Если осталось меньше 8 пикселей -> переходим к последнему
    
    ld   (hl), 0xFF         ; Заливаем все 8 пикселей
    inc  l                  ; Переходим к следующему байту
    
    ld   a, d
    sub  8
    ld   d, a               ; Уменьшаем остаток длины
    jr   .whole_loop

    ; Рисуем последний кусочек линии (остаток пикселей слева в байте)
.last_byte:
    ld   a, d
    and  a
    ret  z                  ; Если остаток ровно 0, то всё готово!
    
    ; Мгновенно берем маску по индексу D (остаток пикселей)
    ld   e, d               ; Индекс в младший байт
    ld   d, HIGH MaskLeftTable
    ld   a, (de)            ; Получили абсолютно точную маску
    
    or   (hl)
    ld   (hl), a
    ret

    ; --- Сценарий: Линия заканчивается ровно на границе первого байта ---
.one_byte_full:
    ld   a, HIGH MaskRightTable
    ld   ixh, a
    ld   a, (ix+0)          ; Индекс E уже в младшем байте IX
    or   (hl)
    ld   (hl), a
    ret

    ; --- Сценарий: Вся линия лежит внутри ОДНОГО байта ---
.one_byte:
    push hl                 ; Сохраняем адрес экрана

    ; 1. Получаем маску правого края
    ld   a, HIGH MaskRightTable
    ld   ixh, a
    ld   a, (ix+0)          ; Читаем по индексу E
    ld   b, a               ; B = маска справа

    ; 2. Получаем маску левого края (длина конца линии от начала байта: E + D)
    ld   a, e
    add  a, d               ; A = смещение конца линии
    ld   e, a
    ld   d, HIGH MaskLeftTable
    ld   a, (de)            ; Маска левой границы отрезка
    
    and  b                  ; Финальная изолированная маска отрезка
    ld   b, a
    
    ; 3. Выводим на экран
    pop  hl                 
    ld   a, b               
    or   (hl)
    ld   (hl), a
    ret

; ============================================================
; ТАБЛИЦЫ МАСОК И АДРЕСОВ (Полностью выровненные по 256 байт)
; ============================================================

    ALIGN 256
BitTable:
    REPT 32
    DB 0x80, 0x40, 0x20, 0x10, 0x08, 0x04, 0x02, 0x01
    ENDR

    ALIGN 256
Table_H:
_Y  = 0
    DUP 192
        DB 0x40 + ((_Y / 64) * 8) + (_Y % 8)
_Y  = _Y + 1
    EDUP
    REPT 64
        DB 0
    ENDR

    ALIGN 256
Table_L:
_Y  = 0
    DUP 192
        DB ((_Y % 64) / 8) * 32
_Y  = _Y + 1
    EDUP
    REPT 64
        DB 0
    ENDR

    ALIGN 256
MaskRightTable:
    ; Маски для пикселей от индекса N до конца байта (0..7)
    DB 0xFF, 0x7F, 0x3F, 0x1F, 0x0F, 0x07, 0x03, 0x01
    REPT 248
        DB 0
    ENDR

    ALIGN 256
MaskLeftTable:
    ; Маски для пикселей от начала байта до индекса N (0..8)
    DB 0x00, 0x80, 0xC0, 0xE0, 0xF0, 0xF8, 0xFC, 0xFE, 0xFF
    REPT 247
        DB 0
    ENDR


; *************************************************************
; DrawVLine — рисует вертикальную линию
;   Input:  B = Y (0..191) — начальный пиксель сверху
;           C = X (0..255)
;           A = L (1..192) — длина в пикселях (вниз)
;   Портит: A, BC, DE, HL
; *************************************************************
DrawVLine:
    and  a
    ret  z                  ; Если длина 0, сразу выходим
    
    push af                 ; [Стек: длина линии]
    
    ; --- 1. Мгновенно получаем маску пикселя по X ---
    ld   d, HIGH BitTable
    ld   e, c               ; DE указывает на нужную маску в таблице
    ld   a, (de)
    push af                 ; [Стек: длина линии, маска пикселя]

    ; --- 2. Вычисляем смещение столбца (X / 8) ---
    ld   a, c
    rrca
    rrca
    rrca
    and  0x1F
    ld   c, a               ; ТЕПЕРЬ В C ХРАНИТСЯ СМЕЩЕНИЕ СТОЛБЦА (0..31)

    ; --- 3. Подготавливаем регистры для быстрого цикла ---
    pop  af                 ; Извлекаем маску пикселя в A
    ld   e, a               ; E = маска пикселя (будет храниться здесь весь цикл)
    
    pop  af                 ; Извлекаем длину линии в A
    ld   ixl, a             ; Прячем длину в ixl (вне цикла это безопасно)
                            ; Теперь распределение:
                            ; B = текущий Y
                            ; C = смещение столбца (X / 8)
                            ; E = маска пикселя

.v_loop:
    ; 1. Находим старший байт адреса (H) по индексу Y (из B)
    ld   d, HIGH Table_H
    ld   h, d               ; Старший байт адреса таблицы Table_H
    ld   l, b               ; Младший байт — это координата Y
    ld   a, (hl)            ; Считали точный H экрана
    push af                 ; Временно спрячем H в стек

    ; 2. Находим младший байт адреса (L) по индексу Y (из B)
    ld   d, HIGH Table_L
    ld   h, d               ; Старший байт адреса таблицы Table_L
    ; l по-прежнему равен b (координате Y)
    ld   a, (hl)            ; Считали базовый L строки (RRR00000)
    
    ; 3. Собираем финальный HL экрана
    or   c                  ; Склеиваем со столбцом X/8
    ld   l, a               ; L готов
    pop  af                 ; Восстанавливаем H экрана
    ld   h, a               ; H готов. В HL идеальный адрес пикселя!

    ; 4. Выводим точку на экран
    ld   a, e               ; A = маска пикселя
    or   (hl)
    ld   (hl), a            ; Наложили пиксель

    ; 5. Переходим к следующей строке вниз
    inc  b                  ; Y = Y + 1
    
    ; 6. Проверяем счетчик длины
    dec  ixl                ; Уменьшаем длину линии
    jr   nz, .v_loop        ; Если не 0, продолжаем рисовать вниз
    ret
