    DEVICE ZXSPECTRUM48
    ORG 32768

Start:

    ld c, 0      ; x
    ld b, 0      ; y

MainCycle:
    call SetPoint1      ; Ставим точку
    inc c               ; Переходим к следующему x
    jr nz, MainCycle    ; Если не ноль, ставим следующую точку
    inc b               ; А если x==0, то увеличиваем y на единицу
    ld a, b
    cp 176              ; Проверяем, достигли ли последней требуемой строки
    jr nz, MainCycle    ;
    
    ret                 ; Выход из программы

; --- Ваша подпрограмма SetPoint1, использующая ПЗУ ---
SetPoint2:
    push bc          ; Сохраняем наши цикловые регистры X и Y

    ; Шаг 1: Кладем Y (из регистра B) на стек калькулятора BASIC
    ld a, c
    call $2D28       ; ПЗУ: STACK-A (кладет значение из A на стек калькулятора)

    ; Шаг 2: Кладем X (из регистра C) на стек калькулятора BASIC
    pop bc           ; Временно достаем BC, чтобы забрать C
    push bc          ; И снова прячем в стек для цикла
    ld a, b          ; Переносим X в A
    call $2D28       ; ПЗУ: STACK-A (теперь X тоже на стеке калькулятора)

    ; Шаг 3: Вызываем штатный PLOT ПЗУ
    call $22DC       ; ПЗУ: ПОЛНЫЙ PLOT (заберет координаты со стека,
                     ; учтет INK/PAPER/OVER и нарисует точку)

    pop bc           ; Восстанавливаем оригинальные B и C для MainCycle
    ret

SetPoint1:
    ; Вход: B = Y (0..191), C = X (0..255)
    ; Портит: A, DE, HL

    ld   a, b
    cp   64                 ; Проверяем, это 1-я треть?
    jr   c, .top_third      ; Если Y < 64, прыгаем на верхнюю треть
    cp   128                ; Проверяем, это 2-я треть?
    jr   c, .mid_third      ; Если Y < 128, прыгаем на среднюю треть

; --- НИЖНЯЯ ТРЕТЬ (Y: 128..191) ---
.bot_third:
    and  0x07
    or   0x50               ; База для 3-й трети: 0x40 + 0x10 = 0x50
    ld   h, a
; --- ОБЩЕЕ БЫСТРОЕ ВЫЧИСЛЕНИЕ L И ЗАПИСЬ ---
    ; Сборка L без мусора третей
    ld   a, b
    add  a, a
    add  a, a               ; Быстрое умножение на 4 вместо rla
    and  0xE0               ; Выделяем RRR в битах 5, 6, 7
    ld   l, a

    ; Добавляем X / 8
    ld   a, c
    rrca
    rrca
    rrca                    ; Крутим X вправо на 3 бита
    and  0x1F               ; Оставляем чистые 5 бит столбца (0..31)
    or   l
    ld   l, a               ; HL полностью готов!

    ; --- Новое получение маски пикселя (БЕЗ and 7 и БЕЗ сложений) ---
    ld   d, HIGH(BitTable) ; Старший байт адреса таблицы (высокая скорость)
    ld   e, c                 ; Младший байт — это напрямую координата X (0..255)
    ld   a, (de)              ; Маска получена мгновенно!

    ; Вывод
    or   (hl)
    ld   (hl), a
    ret

; --- ВЕРХНЯЯ ТРЕТЬ (Y: 0..63) ---
.top_third:
    and  0x07
    or   0x40               ; База для 1-й трети: 0x40
    ld   h, a
; --- ОБЩЕЕ БЫСТРОЕ ВЫЧИСЛЕНИЕ L И ЗАПИСЬ ---
    ; Сборка L без мусора третей
    ld   a, b
    add  a, a
    add  a, a               ; Быстрое умножение на 4 вместо rla
    and  0xE0               ; Выделяем RRR в битах 5, 6, 7
    ld   l, a

    ; Добавляем X / 8
    ld   a, c
    rrca
    rrca
    rrca                    ; Крутим X вправо на 3 бита
    and  0x1F               ; Оставляем чистые 5 бит столбца (0..31)
    or   l
    ld   l, a               ; HL полностью готов!

    ; --- Новое получение маски пикселя (БЕЗ and 7 и БЕЗ сложений) ---
    ld   d, HIGH(BitTable) ; Старший байт адреса таблицы (высокая скорость)
    ld   e, c                 ; Младший байт — это напрямую координата X (0..255)
    ld   a, (de)              ; Маска получена мгновенно!

    ; Вывод
    or   (hl)
    ld   (hl), a
    ret

; --- СРЕДНЯЯ ТРЕТЬ (Y: 64..127) ---
.mid_third:
    and  0x07
    or   0x48               ; База для 2-й трети: 0x40 + 0x08 = 0x48
    ld   h, a
; --- ОБЩЕЕ БЫСТРОЕ ВЫЧИСЛЕНИЕ L И ЗАПИСЬ ---
    ; Сборка L без мусора третей
    ld   a, b
    add  a, a
    add  a, a               ; Быстрое умножение на 4 вместо rla
    and  0xE0               ; Выделяем RRR в битах 5, 6, 7
    ld   l, a

    ; Добавляем X / 8
    ld   a, c
    rrca
    rrca
    rrca                    ; Крутим X вправо на 3 бита
    and  0x1F               ; Оставляем чистые 5 бит столбца (0..31)
    or   l
    ld   l, a               ; HL полностью готов!

    ; --- Новое получение маски пикселя (БЕЗ and 7 и БЕЗ сложений) ---
    ld   d, HIGH(BitTable) ; Старший байт адреса таблицы (высокая скорость)
    ld   e, c                 ; Младший байт — это напрямую координата X (0..255)
    ld   a, (de)              ; Маска получена мгновенно!

    ; Вывод
    or   (hl)
    ld   (hl), a
    ret

    ALIGN 256
BitTable:
    REPT 32
    DB 0x80, 0x40, 0x20, 0x10, 0x08, 0x04, 0x02, 0x01
    ENDR



    
Delay:
    push bc
    ld bc, 0xFFF
Delay1:
    dec bc
    ld a,b
    or c
    jr nz, Delay1
    pop bc
    ret
    


program_length = $-Start

