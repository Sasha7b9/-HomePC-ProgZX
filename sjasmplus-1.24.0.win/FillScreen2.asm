    DEVICE ZXSPECTRUM48
    ORG 32768

Start:

    ld c, 0      ; x
    ld b, 0      ; y

MainCycle:
    call SetPoint1      ; Ставим точку
    inc c               ; Переходим к следующему x
    jr nz, MainCycle    ; Если не ноль, ставим следующую точку
    inc b               ; А если x==0, то увеличиваем y на единицу
    ld a, b
    cp 176              ; Проверяем, достигли ли последней требуемой строки
    jr nz, MainCycle    ;
    
    ret                 ; Выход из программы

; --- Ваша подпрограмма SetPoint1, использующая ПЗУ ---
SetPoint2:
    push bc          ; Сохраняем наши цикловые регистры X и Y

    ; Шаг 1: Кладем Y (из регистра B) на стек калькулятора BASIC
    ld a, c
    call $2D28       ; ПЗУ: STACK-A (кладет значение из A на стек калькулятора)

    ; Шаг 2: Кладем X (из регистра C) на стек калькулятора BASIC
    pop bc           ; Временно достаем BC, чтобы забрать C
    push bc          ; И снова прячем в стек для цикла
    ld a, b          ; Переносим X в A
    call $2D28       ; ПЗУ: STACK-A (теперь X тоже на стеке калькулятора)

    ; Шаг 3: Вызываем штатный PLOT ПЗУ
    call $22DC       ; ПЗУ: ПОЛНЫЙ PLOT (заберет координаты со стека,
                     ; учтет INK/PAPER/OVER и нарисует точку)

    pop bc           ; Восстанавливаем оригинальные B и C для MainCycle
    ret

SetPoint1:
    ; Вход: B = Y (0..191), C = X (0..255)
    ; Портит: A, DE, HL

    ; --- 1. Вычисляем старший байт адреса (H) ---
    ld   a, b
    and  0x07       ; A = 00000FFF (строка внутри знакоместа)
    or   0x40       ; A = 01000FFF (базовая страница экрана)
    ld   h, a       ; Сохраняем в H

    ld   a, b
    rra
    rra
    rra             ; Сдвигаем Y вправо на 3 бита. 
    and  0x18       ; Теперь в битах 3 и 4 железно сидят трети экрана (TT)
    or   h          ; Склеиваем с H
    ld   h, a       ; Теперь в H идеальный старший байт: 010TTFFF

    ; --- 2. Вычисляем младший байт адреса (L) ---
    ld   a, b
    rla
    rla             ; Сдвигаем влево. Биты строки знакоместа (RRR) 
    and  0xE0       ; встают строго на позиции 5, 6, 7. Остальное — нули.
    ld   l, a       ; Сохраняем в L

    ld   a, c
    srl  a
    srl  a
    srl  a          ; X / 8 (номер столбца 0..31 в битах 0..4)
    or   l          ; Склеиваем столбец и строку знакоместа
    ld   l, a       ; В HL теперь точный адрес байта экрана!

    ; --- 3. Получение маски пикселя ---
    ld   a, c
    and  7          ; A = X % 8

    ld   de, BitTable
    add  a, e       ; Благодаря ALIGN 8 младший байт адреса таблицы 
    ld   e, a       ; никогда не переполнится. inc d не нужен.
    ld   a, (de)    ; Получаем маску из таблицы

    ; --- 4. Запись на экран ---
    or   (hl)       ; Накладываем точку на экран
    ld   (hl), a    ; Записываем обратно
    ret

    ALIGN 8
BitTable:
    DB 0x80, 0x40, 0x20, 0x10, 0x08, 0x04, 0x02, 0x01


    
Delay:
    push bc
    ld bc, 0xFFF
Delay1:
    dec bc
    ld a,b
    or c
    jr nz, Delay1
    pop bc
    ret
    


program_length = $-Start

    include     TapLib.asm
    MakeTape ZXSPECTRUM48, "fill_scr.tap", "FILL_SCR", Start, program_length, Start
